#!/usr/bin/env bash
# Evaluate checkpoints head-to-head against a baseline on one host, detached.
#
#   tools/eval_harness.sh <eval-host> <suite> <baseline-label>=<ckpt> <label>=<ckpt>...
#
#   env: SEEDS   (default "20260910 20261008" -- two seeds per setting, C18 rule;
#                 20260910 matches the C18 legs and the first scale_1m evals)
#        TABLES  (default 120 -> 480 games per seed)
#        WORKERS (default 10)
#        CONFIG  (default the C16 champion search config)
#
# ckpt paths are relative to ~/code/bgai on the eval host; a provenance.json
# beside a checkpoint (tools/snap_ckpts.sh writes one) is stored in each run.
#
# On the eval host, in tmux session "eval-<suite>", for seed in SEEDS, for each
# candidate (seed-major, so one pass over every candidate lands first):
#   data/evals/<suite>/<label>_s<seed>.json   every game (bgai.arena.run --json)
#   data/evals/<suite>/<label>_s<seed>.{log,html}
# after each run the pooled verdict goes to ntfy (topic ~/.config/bgai/ntfy_topic,
# see tools/run_watchdog.sh) and data/evals/<suite>/summary.md is rewritten
# (python -m bgai.arena.compare). A run that already has its .json is skipped,
# so re-launching a suite resumes it. Re-read results any time with:
#   uv run -q python -m bgai.arena.compare --baseline <label> data/evals/<suite>/*_s*.json
set -euo pipefail
host="${1:?eval host}"; suite="${2:?suite name}"; shift 2
[ "$#" -ge 2 ] || { echo "harness: need baseline=ckpt and at least one label=ckpt" >&2; exit 2; }
case "$suite" in *[!A-Za-z0-9_.-]*) echo "harness: suite must be [A-Za-z0-9_.-]" >&2; exit 2 ;; esac
for pair in "$@"; do
  case "$pair" in
    *=*) label="${pair%%=*}"
         case "$label" in ''|*[!A-Za-z0-9_.-]*) echo "harness: bad label in '$pair'" >&2; exit 2 ;; esac ;;
    *) echo "harness: expected label=ckpt, got '$pair'" >&2; exit 2 ;;
  esac
done
seeds="${SEEDS:-20260910 20261008}"
tables="${TABLES:-120}"; workers="${WORKERS:-10}"
config="${CONFIG:-sims=512,top_k=8,max_depth=48,batch=16,c_puct=2.5,temperature=0}"

# ssh joins its arguments into ONE remote command line, so each is %q-escaped:
# unescaped, SEEDS="a b" would arrive as two arguments.
# shellcheck disable=SC2029  # client-side expansion is the point
ssh "$host" "bash -s -- $(printf '%q ' "$suite" "$seeds" "$tables" "$workers" "$config" "$@")" <<'REMOTE'
set -euo pipefail
suite="$1"; seeds="$2"; tables="$3"; workers="$4"; config="$5"; shift 5
base_label="${1%%=*}"; base_ckpt="${1#*=}"; shift
cd ~/code/bgai
for pair in "$base_label=$base_ckpt" "$@"; do
  [ -f "${pair#*=}" ] || { echo "[$(hostname)] missing checkpoint: ${pair#*=}" >&2; exit 1; }
done
session="eval-$suite"
if tmux has-session -t "$session" 2>/dev/null; then
  echo "[$(hostname)] tmux session $session already running" >&2; exit 1
fi
dir="data/evals/$suite"; mkdir -p "$dir"
queue="$dir/queue.sh"
{
  echo '#!/usr/bin/env bash'
  echo '# generated by tools/eval_harness.sh'
  echo 'set -uo pipefail'
  echo 'cd ~/code/bgai; export PATH=$HOME/.local/bin:/snap/bin:$PATH'
  echo 'export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1 POLARS_MAX_THREADS=1'
  cat <<'FUNCS'
notify() {  # notify TITLE BODY -- best effort, never fails the queue
  local t; t=$(tr -d ' \n' < ~/.config/bgai/ntfy_topic 2>/dev/null) || t=""
  [ -n "$t" ] || { echo "notify: no topic, not sent: $1"; return 0; }
  curl -fsS -m 20 -o /dev/null -H "Title: $1" -H "Tags: bgai" -d "$2" "https://ntfy.sh/$t" \
    || echo "notify: POST failed: $1"
}
meta_args() {  # provenance.json beside a checkpoint -> --meta k=v ...
  local prov; prov="$(dirname "$1")/provenance.json"
  [ -f "$prov" ] || return 0
  python3 -c 'import json,sys; [print(f"--meta\n{k}={v}") for k,v in json.load(open(sys.argv[1])).items() if not isinstance(v,(dict,list))]' "$prov"
}
FUNCS
  printf 'suite=%q; dir=%q; tables=%q; workers=%q; config=%q\n' "$suite" "$dir" "$tables" "$workers" "$config"
  printf 'base_label=%q; base_ckpt=%q\n' "$base_label" "$base_ckpt"
  printf 'seeds=(%s)\n' "$seeds"
  printf 'cands=('; for p in "$@"; do printf '%q ' "$p"; done; printf ')\n'
  cat <<'BODY'
total=$(( ${#seeds[@]} * ${#cands[@]} )); n=0; failed=0
for seed in "${seeds[@]}"; do
  for pair in "${cands[@]}"; do
    label="${pair%%=*}"; ckpt="${pair#*=}"; tag="${label}_s${seed}"; n=$((n + 1))
    if [ -s "$dir/$tag.json" ]; then echo "$(date -Is) skip $tag (done)"; continue; fi
    echo "$(date -Is) start $tag ($n/$total)"
    mapfile -t meta < <(meta_args "$ckpt")
    if uv run -q python -u -m bgai.arena.run --tables "$tables" --seed "$seed" --workers "$workers" \
         --report "$dir/$tag.html" --json "$dir/$tag.json" "${meta[@]}" \
         --agents "mcts@$label:ckpt=$ckpt,$config,mcts@$base_label:ckpt=$base_ckpt,$config" \
         > "$dir/$tag.log" 2>&1; then
      verdict=$(uv run -q python -m bgai.arena.compare --brief --baseline "$base_label" \
                  "$dir"/"${label}"_s*.json 2>&1)
      echo "$(date -Is) done $tag: $verdict"
      notify "eval $suite: $tag done ($n/$total)" "$verdict"
    else
      failed=$((failed + 1)); rm -f "$dir/$tag.json"
      echo "$(date -Is) FAILED $tag (see $dir/$tag.log)"; tail -5 "$dir/$tag.log"
      notify "eval $suite: $tag FAILED" "$(tail -3 "$dir/$tag.log")"
    fi
    uv run -q python -m bgai.arena.compare --baseline "$base_label" "$dir"/*_s*.json \
      --json "$dir/summary.json" > "$dir/summary.md" 2>&1 || true
  done
done
notify "eval $suite: finished ($failed failed)" \
  "$(uv run -q python -m bgai.arena.compare --brief --baseline "$base_label" "$dir"/*_s*.json 2>&1)"
echo "$(date -Is) finished, $failed failed"
BODY
} > "$queue"
chmod +x "$queue"
tmux new-session -d -s "$session" "$queue >> $dir/queue.log 2>&1"
echo "[$(hostname)] launched $session: $# candidate(s) x seeds ($seeds), $tables tables, $workers workers"
echo "[$(hostname)] log: ~/code/bgai/$dir/queue.log  summary: ~/code/bgai/$dir/summary.md"
REMOTE
